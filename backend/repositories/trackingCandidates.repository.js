const { createRepository, dateValue } = require("./base.repository");

module.exports = createRepository({
  table: "tracking_candidates",
  jsonKey: "trackingCandidates",
  columns: [
    { name: "session_id", value: (item) => item.sessionId },
    { name: "observation_id", value: (item) => item.observationId },
    { name: "camera_id", value: (item) => item.cameraId },
    { name: "detected_at", value: (item) => dateValue(item.detectedAt) },
    { name: "appearance_similarity", value: (item) => item.appearanceSimilarity ?? null },
    { name: "spatial_consistency", value: (item) => item.spatialConsistency ?? null },
    { name: "timing_consistency", value: (item) => item.timingConsistency ?? null },
    { name: "direction_consistency", value: (item) => item.directionConsistency ?? null },
    { name: "activity_consistency", value: (item) => item.activityConsistency ?? null },
    { name: "plate_similarity", value: (item) => item.plateSimilarity ?? null },
    { name: "color_similarity", value: (item) => item.colorSimilarity ?? null },
    { name: "vehicle_type_similarity", value: (item) => item.vehicleTypeSimilarity ?? null },
    { name: "brand_model_similarity", value: (item) => item.brandModelSimilarity ?? null },
    { name: "distinctive_marks_similarity", value: (item) => item.distinctiveMarksSimilarity ?? null },
    { name: "speed_consistency", value: (item) => item.speedConsistency ?? null },
    { name: "route_consistency", value: (item) => item.routeConsistency ?? null },
    { name: "overall_confidence", value: (item) => item.overallConfidence },
    { name: "status", value: (item) => item.status },
    { name: "match_explanation", value: (item) => JSON.stringify(item.matchExplanation || {}) },
    { name: "reviewed_at", value: (item) => item.reviewedAt ? dateValue(item.reviewedAt) : null },
    { name: "reviewed_by", value: (item) => item.reviewedBy || null },
    { name: "review_reason", value: (item) => item.reviewReason || null },
    { name: "created_at", value: (item) => dateValue(item.createdAt) }
  ],
  deserialize: (row) => ({
    id: row.id,
    sessionId: row.session_id,
    observationId: row.observation_id,
    cameraId: row.camera_id,
    detectedAt: row.detected_at,
    appearanceSimilarity: row.appearance_similarity,
    spatialConsistency: row.spatial_consistency,
    timingConsistency: row.timing_consistency,
    directionConsistency: row.direction_consistency,
    activityConsistency: row.activity_consistency,
    plateSimilarity: row.plate_similarity,
    colorSimilarity: row.color_similarity,
    vehicleTypeSimilarity: row.vehicle_type_similarity,
    brandModelSimilarity: row.brand_model_similarity,
    distinctiveMarksSimilarity: row.distinctive_marks_similarity,
    speedConsistency: row.speed_consistency,
    routeConsistency: row.route_consistency,
    overallConfidence: row.overall_confidence,
    status: row.status,
    matchExplanation: row.match_explanation || {},
    reviewedAt: row.reviewed_at,
    reviewedBy: row.reviewed_by,
    reviewReason: row.review_reason,
    data: row.data || {},
    createdAt: row.created_at
  })
});